// =============================================================================
// sum.c —— 一个"麻雀虽小五脏俱全"的 C 源文件，专门用来观察 LLVM 编译全流程
// -----------------------------------------------------------------------------
// 为什么选这段代码？因为它同时包含了三个能在 IR/汇编里看出门道的要素：
//   1. 一个小函数 square()      —— 在 -O2 下会被【内联(inline)】进循环
//   2. 一个带循环的 sum_of_squares() —— -O0 下用 alloca/load/store 表示局部变量，
//                                       跑 mem2reg 后会变成 SSA 的 phi 节点（重点！）
//   3. main() 里调用 printf     —— 保证能真正链接成可执行文件并运行
// =============================================================================

#include <stdio.h>

// 会被内联的小函数：求平方
int square(int x) {
    return x * x;
}

// 带循环的函数：计算 1^2 + 2^2 + ... + n^2
//   n = 5 时结果 = 1 + 4 + 9 + 16 + 25 = 55
int sum_of_squares(int n) {
    int acc = 0;                       // 局部变量 -> -O0 下是一块 alloca 内存
    for (int i = 1; i <= n; i++) {     // 循环 -> 会产生多个基本块 + 分支
        acc += square(i);              // 函数调用 -> -O2 下被内联展开
    }
    return acc;
}

int main(void) {
    int n = 5;
    printf("sum_of_squares(%d) = %d\n", n, sum_of_squares(n));
    return 0;
}
